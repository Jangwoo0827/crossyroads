export const SHADOW_TINT = 0x4a4458;

export function buildCharacter(id: string): THREE.Group {
  const parts = DEFS[id] ?? DEFS.chicken;
  const g = new THREE.Group();
  for (const [w, h, d, x, y, z, c] of parts) {
    const m = new THREE.Mesh(box, colorMat(c));
    m.scale.set(w, h, d);
    m.position.set(x, y, z);
    m.castShadow = true;
    g.add(m);
  }
  return g;
}

/** 잠긴 캐릭터는 어두운 실루엣으로 */
export function buildLockedCharacter(id: string): THREE.Group {
  const g = buildCharacter(id);
  g.children.forEach((c) => ((c as THREE.Mesh).material = colorMat(SHADOW_TINT)));
  return g;
}
